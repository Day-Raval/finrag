"""Ablation tables built from saved reports, no LLM calls.

Run from the repo root:  python -m finrag.evaluation.ablation

Reads reports/retrieval/<config>.json and reports/runs/<run>/ (summary.json and
judge files) and writes reports/ablation.md: one row per component tried, with
the decision taken. Rerun it after any new experiment; CI checks it is current.
"""

import json
from pathlib import Path

from finrag.evaluation.judge import SCORES
from finrag.evaluation.score_run import mean

# (report name, what changed, decision). Order = order the components were added.
RETRIEVAL = [
    ("dense_fixed_512_64", "Baseline: dense, fixed 512/64 chunks", "Starting point"),
    ("section_512", "Section-aware chunks (1.11)", "Dropped: ties the baseline"),
    ("fixed_512_64_hdr", "+ contextual header (1.12)", "Kept: section recall +0.109"),
    ("hdr_hybrid", "+ hybrid BM25 alone (1.13)", "Not alone: pulls other companies' filings"),
    ("hdr_filter", "+ company/year filter alone (1.14)", "Kept: biggest single gain"),
    ("hdr_hybrid_filter", "+ hybrid + filter (1.13 + 1.14)", "Kept: MRR 0.408 -> 0.658"),
    ("hdr_hf_rerank", "+ MiniLM cross-encoder (1.15)", "Dropped: lowers MRR"),
    ("hdr_hf_rerank_bge", "+ bge-reranker-base (1.15)", "Dropped: lowers MRR, +2.4 s on GPU"),
    ("hdr_hf_decomp_company", "+ per-company coverage (1.16)", "Kept: doc recall 1.0, free"),
]
RUNS = [
    ("dev_baseline", "Baseline retrieval, prompt v1", "Starting point"),
    ("dev_retrieval", "Final retrieval (1.12-1.16), prompt v1", "Kept: final configuration"),
    ("dev_prompt_v2", "+ prompt v2: calculate, answer every part (1.17)", "Dropped: less faithful, fewer citations"),
    ("dev_prompt_v3", "+ prompt v3: v1 + definitions, no guessing (1.17)", "Dropped: least faithful"),
]
FINAL = (
    "`configs/hdr_hf_decomp_company.yaml` with `prompts/answer_v1.md`: contextual "
    "headers, hybrid BM25 + dense search, company/year filter, and per-company "
    "coverage; no reranker; the original short prompt."
)


def fmt(value, digits: int = 3) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def judge_score(path: Path, kind: str) -> float | None:
    """Mean judge score on answerable questions; the last verdict per question wins."""
    if not path.exists():
        return None
    rows = {r["id"]: r for r in map(json.loads, path.read_text().splitlines())}
    return mean([SCORES[kind].get(r["verdict"]) for r in rows.values() if r["category"] != "unanswerable"])


def retrieval_row(reports: Path, name: str, label: str, decision: str) -> str:
    path = reports / "retrieval" / f"{name}.json"
    d = json.loads(path.read_text()) if path.exists() else {"overall": {}}
    s = d["overall"]
    cells = [s.get("section_recall"), s.get("doc_recall"), s.get("mrr"), s.get("section_recall@3")]
    return f"| {label} | `{name}` | " + " | ".join(map(fmt, cells)) + f" | {fmt(d.get('p95_s'), 2)} | {decision} |"


def run_row(reports: Path, name: str, label: str, decision: str) -> str:
    run = reports / "runs" / name
    summary = json.loads((run / "summary.json").read_text()) if (run / "summary.json").exists() else {}
    tokens = summary.get("tokens_per_question")
    cells = [
        fmt(judge_score(run / "judge_correctness.jsonl", "correctness")),
        fmt(judge_score(run / "judge_faithfulness.jsonl", "faithfulness")),
        fmt(summary.get("false_refusal_rate")),
        fmt(summary.get("overall", {}).get("citation")),
        fmt(summary.get("p95_s"), 1),
        "—" if tokens is None else f"{tokens:,}",
        "—" if tokens is None else f"{tokens / 1000:.1f}M",
    ]
    return f"| {label} | `{name}` | " + " | ".join(cells) + f" | {decision} |"


def build(reports: Path) -> str:
    lines = [
        "# Ablation",
        "",
        "Generated by `python -m finrag.evaluation.ablation` from the saved reports; do not edit by hand.",
        "",
        "## Retrieval (69 answerable golden questions, top 5, no LLM calls)",
        "",
        "| Component | Config | Section recall@5 | Doc recall@5 | MRR | Section recall@3 | Search p95 (s) | Decision |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |",
        *(retrieval_row(reports, *r) for r in RETRIEVAL),
        "",
        "## Answers (24-question dev subset; quality metrics on its 21 answerable questions)",
        "",
        "| Component | Run | Correctness | Faithfulness | False refusals | Citation | p95 (s) | Tokens / question | Tokens / 1k queries | Decision |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
        *(run_row(reports, *r) for r in RUNS),
        "",
        "One dev question is worth about 0.05, and the judge can move a borderline answer",
        "between partial and incorrect, so answer-level differences under about 0.05 are noise.",
        "Groq's free tier costs $0; a paid estimate is tokens / 1k queries x the price per token.",
        "",
        "## Final configuration",
        "",
        FINAL,
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    out = Path("reports/ablation.md")
    out.write_text(build(Path("reports")))
    print(out.read_text())


if __name__ == "__main__":
    main()